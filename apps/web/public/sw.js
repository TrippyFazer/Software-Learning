/* =============================================================================
   Infrastructure Learning Lab — service worker
   =============================================================================
   Written by hand rather than generated by Workbox: this file is itself course
   material, and a 40 kB dependency that hides what the browser is doing would
   defeat the point.

   THE ONE RULE THAT MATTERS

   A service worker sits between the app and the network permanently. Get it
   wrong and you do not ship a bug — you ship a bug that CANNOT be fixed by
   deploying, because the broken worker keeps serving the broken app. So:

     * every cache name carries VERSION, and activate deletes everything else
     * navigations are network-FIRST, so a deploy is picked up as soon as the
       device is online, and the cache is only a fallback
     * only /assets/* is cache-first, and only because Vite hashes those
       filenames — the hash IS the version, so a stale hit is impossible

   WHAT IS DELIBERATELY NOT HERE

   Writes. Nothing that changes learner state is cached, replayed or retried by
   this worker. Progress is queued by the application in IndexedDB (see
   src/offline.ts) where it is visible, inspectable and cancellable by the
   learner. A service worker silently replaying POSTs hours later is how people
   end up with duplicated or resurrected data they never authorised.
   ============================================================================= */

const VERSION = "ill-v1";
const SHELL = `${VERSION}-shell`;       // index.html, JS/CSS bundles, icons
const CONTENT = `${VERSION}-content`;   // GET /api/content/* — the curriculum

/* The curriculum is version-controlled Markdown and YAML: identical for every
   learner, changing only on deploy. That is what makes it safe to cache
   aggressively — unlike anything under /api/learning, which is personal. */
const SHELL_PRECACHE = [
  "/",
  "/manifest.webmanifest",
  "/icon.svg",
  "/icon-192.png",
  "/icon-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(SHELL)
      // addAll is atomic — one 404 fails the whole install. That is wanted:
      // a half-populated shell cache is worse than none, because it looks
      // like it worked.
      .then((c) => c.addAll(SHELL_PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => !k.startsWith(VERSION)).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

/* The app asks for two things directly. */
self.addEventListener("message", (event) => {
  const msg = event.data || {};
  if (msg.type === "SKIP_WAITING") self.skipWaiting();
  // Logout: the identity and any personal response must not outlive the
  // session, even though we cache very little of it.
  if (msg.type === "PURGE") {
    event.waitUntil(caches.keys().then((k) => Promise.all(k.map((n) => caches.delete(n)))));
  }
});

function isContent(url) {
  return url.pathname.startsWith("/api/content/");
}

/* Two READ-ONLY projections of personal state that offline reading depends on.
   Without them "flashcards work offline" is false: the due list comes from
   /api/learning, so the Review page would spin on "loading…" forever with a
   fully populated card cache sitting right there.

   They are network-FIRST, so while online you always see the truth; the cache
   is only ever a fallback. Both degrade harmlessly when stale — you review the
   cards that were due when you last had signal, and a lesson you completed
   offline shows as complete once the queue drains.

   Deliberately NOT extended to /api/learning/progress or /mastery. Those are
   SCORES. A number that looks authoritative and is quietly hours out of date
   is worse than an honest blank. */
const READ_ONLY_STATE = ["/api/learning/flashcards/due", "/api/learning/lessons/progress"];

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);

  // Never touch other origins, and never interfere with a write.
  if (req.method !== "GET" || url.origin !== self.location.origin) return;

  // --- hashed build output: cache-first ------------------------------------
  // Safe ONLY because the filename contains a content hash. Never do this for
  // a path whose contents can change.
  if (url.pathname.startsWith("/assets/")) {
    event.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(SHELL).then((c) => c.put(req, copy));
            }
            return res;
          }),
      ),
    );
    return;
  }

  // --- curriculum: stale-while-revalidate ----------------------------------
  // Answer instantly from cache when we have it, and refresh in the
  // background so the next visit is current. On a plane the fetch simply
  // fails and the cached copy is all there is — which is the entire point.
  if (isContent(url)) {
    event.respondWith(
      caches.open(CONTENT).then(async (cache) => {
        const hit = await cache.match(req);
        const network = fetch(req)
          .then((res) => {
            if (res.ok) cache.put(req, res.clone());
            return res;
          })
          .catch(() => undefined);
        if (hit) {
          event.waitUntil(network);
          return hit;
        }
        const res = await network;
        if (res) return res;
        // Nothing cached and no network: say so honestly in the shape the
        // client already parses, rather than throwing an opaque TypeError.
        return new Response(
          JSON.stringify({ detail: "Not available offline — download it while online first." }),
          { status: 503, headers: { "Content-Type": "application/json" } },
        );
      }),
    );
    return;
  }

  // --- read-only personal projections: network-first, cache fallback -------
  if (READ_ONLY_STATE.includes(url.pathname)) {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CONTENT).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() =>
          caches.match(req, { cacheName: CONTENT }).then(
            (hit) =>
              hit ||
              new Response(JSON.stringify({ detail: "Not available offline." }), {
                status: 503,
                headers: { "Content-Type": "application/json" },
              }),
          ),
        ),
    );
    return;
  }

  // --- everything else under /api: network only ----------------------------
  // Scores and writes are never served stale. A wrong mastery number is worse
  // than an honest failure.
  if (url.pathname.startsWith("/api/")) return;

  // --- navigations: network-first, cached shell as fallback ----------------
  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(SHELL).then((c) => c.put("/", copy));
          }
          return res;
        })
        // Any URL falls back to the SPA shell: client-side routing takes it
        // from there, so a deep link opened offline still lands correctly.
        .catch(() => caches.match("/", { cacheName: SHELL }).then((h) => h || Response.error())),
    );
    return;
  }

  // Remaining same-origin GETs (icons, manifest): cache-first, network fill.
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(SHELL).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
